// Text and quoted HTML attribute encoding. Do not use for JavaScript/CSS or
// to validate URL protocols; keep trusted markup outside this helper.
export function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[character]);
}
